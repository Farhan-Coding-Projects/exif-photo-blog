export type CameraMakeMark = keyof typeof CAMERA_MAKE_MARKS;

export const getCameraMakeMark = (
  make = '',
): CameraMakeMark | undefined =>
  isMakeSamsung(make) ? 'samsung'
    : isMakeSony(make) ? 'sony'
      : isMakeDji(make) ? 'dji'
        : /\bcanon/i.test(make) ? 'canon'
          : undefined;

export default function IconCameraMake({
  mark,
  className,
}: {
  mark: CameraMakeMark
  className?: string
}) {
  const { label, viewBox, path } = CAMERA_MAKE_MARKS[mark];
  return (
    <svg
      role="img"
      viewBox={viewBox}
      width={14}
      height={12}
      fill="currentColor"
      className={className}
    >
      <title>{label}</title>
      <path d={path} />
    </svg>
  );
}
